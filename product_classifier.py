# 기본 카테고리 (분류되지 않는 품목용)
DEFAULT_CATEGORY = {"대분류": "기타", "중분류": "기타"}


def classify_item(item_name):
    """
    품목명을 기반으로 카테고리 분류
    Returns: (대분류, 중분류)
    """
    if pd.isna(item_name) or str(item_name).strip() == "":
        return DEFAULT_CATEGORY["대분류"], DEFAULT_CATEGORY["중분류"]

    item = str(item_name).strip()
    item_lower = item.lower()

    # 규칙 매칭
    for keyword, category in CATEGORY_RULES.items():
        if keyword in item_lower or keyword in item:
            return category["대분류"], category["중분류"]

    # 키워드 확장 매칭 (부분 일치 기반)
    # 음료 관련
    if any(kw in item_lower for kw in ["커피", "라떼", "아메리카노", "에스프레소", "카푸치노", "모카", "차", "티", "녹차", "홍차", "주스", "에이드", "스무디", "밀크쉐이크", "생수", "물", "탄산", "콜라", "사이다", "우유", "두유", "요거트", "음료"]):
        return "음료", "기타음료"

    # 베이커리/간식
    if any(kw in item_lower for kw in ["빵", "식빵", "크로아상", "도넛", "케이크", "마카롱", "쿠키", "초콜릿", "사탕", "아이스크림", "와플", "브라우니", "머핀"]):
        return "베이커리", "기타"

    # 식사/요리
    if any(kw in item_lower for kw in ["김밥", "비빔밥", "찌개", "불고기", "잡채", "라면", "떡볶이", "튀김", "돈까스", "초밥", "우동", "파스타", "피자", "햄버거", "샐러드", "샌드위치", "국밥", "덮밥", "볶음밥"]):
        return "식사", "기타"

    # 과일/채소
    if any(kw in item_lower for kw in ["사과", "바나나", "포도", "딸기", "오렌지", "귤", "수박", "토마토", "상추", "배추", "당근", "양파", "감자", "오이", "고추", "마늘", "생강"]):
        return "신선식품", "기타"

    # 생활용품
    if any(kw in item_lower for kw in ["세면", "샴푸", "비누", "치약", "휴지", "물티슈", "장갑", "마스크", "세제", "섬유유연제"]):
        return "생활용품", "기타"

    # 화장품
    if any(kw in item_lower for kw in ["로션", "크림", "선크림", "파운데이션", "립스틱", "향수", "클렌징", "토너", "에센스", "세럼", "선블록"]):
        return "화장품", "기타"

    # 패션/의류
    if any(kw in item_lower for kw in ["티셔츠", "셔츠", "바지", "원피스", "자켓", "코트", "신발", "운동화", "구두", "가방", "모자", "양말", "속옷"]):
        return "패션", "기타"

    # 전자/디지털
    if any(kw in item_lower for kw in ["스마트폰", "태블릿", "노트북", "마우스", "키보드", "충전기", "이어폰", "스피커", "모니터", "프린터"]):
        return "전자제품", "기타"

    # 취미/레저
    if any(kw in item_lower for kw in ["운동화", "자전거", "캠핑", "낚시", "골프", "책", "퍼즐", "보드게임"]):
        return "레저/스포츠", "기타"

    # 반려동물
    if any(kw in item_lower for kw in ["사료", "간식", "장난감", "리드줄", "목줄", "캣타워", "캣타워"]):
        return "반려동물", "기타"

    return DEFAULT_CATEGORY["대분류"], DEFAULT_CATEGORY["중분류"]


def classify_products():
    """품목명 분류 실행"""
    workspace = Path(__file__).parent

    # 데이터 로드
    orders_path = workspace / "data" / "orders.csv"
    if not orders_path.exists():
        print(f"[ERROR] {orders_path} 파일을 찾을 수 없습니다.")
        # 대체: workspace 루트의 orders.csv
        orders_path = workspace / "orders.csv"

    if not orders_path.exists():
        print(f"[ERROR] orders.csv 파일을 찾을 수 없습니다.")
        print("  data/orders.csv 또는 orders.csv 에 item_name 컬럼이 필요합니다.")
        return

    orders = pd.read_csv(orders_path, dtype=str)

    # item_name 컬럼 확인
    if "item_name" not in orders.columns:
        print("[ERROR] orders.csv 에 item_name 컬럼이 없습니다.")
        return

    # 품목명 추출 및 분류
    product_df = orders[["order_id", "item_name", "order_date", "customer_id"]].copy()
    product_df["대분류"] = product_df["item_name"].apply(lambda x: classify_item(x)[0])
    product_df["중분류"] = product_df["item_name"].apply(lambda x: classify_item(x)[1])

    # 분류 결과 저장
    workspace.mkdir(exist_ok=True)
    output_dir = workspace / "output"
    output_dir.mkdir(exist_ok=True)

    product_df.to_csv(output_dir / "product_classification.csv", index=False, encoding="utf-8-sig")
    print(f"✅ 품목명 분류 완료: {len(product_df)}건")
    print(f"  대분류별 분포:")
    print(product_df["대분류"].value_counts().to_string())
    print(f"  저장: output/product_classification.csv")

    # 카테고리별 요약
    category_summary = product_df.groupby(["대분류", "중분류"]).agg(
        품목_건수=("order_id", "count"),
        고유_고객수=("customer_id", "nunique")
    ).reset_index()
    category_summary.to_csv(output_dir / "category_summary.csv", index=False, encoding="utf-8-sig")
